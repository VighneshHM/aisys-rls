"""Generate docs/data-dictionary.md and docs/api-reference.md from the code, so they cannot drift from it.

    python scripts/gen_docs.py            # rewrite both files
    python scripts/gen_docs.py --check    # exit 1 if either file is out of date (used by a test)

The data dictionary reads the SQLAlchemy models (tables, columns, types, keys, indexes) and draws the entity-relationship
diagram. The API reference reads the FastAPI routes (method, path, who may call it, what it does).
"""

# ruff: noqa: E501  (this script writes prose into documents)
from __future__ import annotations

import argparse
import inspect
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from fastapi.routing import APIRoute  # noqa: E402

from aisys import models  # noqa: E402,F401  (imports register every table)
from aisys.db import Base  # noqa: E402

# links that exist in the data but are plain numbers in the database (see migration 0009)
SOFT_LINKS = [("notifications", "member_id", "members"), ("notifications", "loan_id", "loans")]
OUT_DATA = REPO / "docs" / "data-dictionary.md"
OUT_API = REPO / "docs" / "api-reference.md"


def _doc_of(table) -> str:
    for mapper in Base.registry.mappers:
        if mapper.local_table is table and mapper.class_.__doc__:
            return " ".join(mapper.class_.__doc__.split())
    return ""


def _type(col) -> str:
    text = str(col.type)
    return (
        text.replace("VARCHAR", "text")
        .replace("DATETIME", "datetime")
        .replace("INTEGER", "integer")
        .replace("BOOLEAN", "yes/no")
    )


def data_dictionary() -> str:
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    out = [
        "# Data dictionary",
        "",
        "_Generated by `python scripts/gen_docs.py` from the SQLAlchemy models. Do not edit by hand._",
        "",
        f"{len(tables)} tables. Times are stored with a UTC offset. Every table has an integer `id` primary key unless noted.",
        "The full-text search index `item_fts` (SQLite FTS5, migration 0010) is derived data kept current by triggers and is not listed.",
        "",
        "## Entity-relationship diagram",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for t in tables:
        for fk in sorted(t.foreign_keys, key=lambda f: (f.parent.name, f.column.table.name, f.column.name)):
            out.append(f'  {fk.column.table.name} ||--o{{ {t.name} : "{fk.parent.name}"')
    for child, col, parent in SOFT_LINKS:
        out.append(f'  {parent} ||--o{{ {child} : "{col}"')
    out += ["```", ""]
    out += roles_matrix()
    for t in tables:
        out += [f"## `{t.name}`", ""]
        doc = _doc_of(t)
        if doc:
            out += [doc, ""]
        out += ["| Column | Type | Required | Notes |", "|---|---|---|---|"]
        unique_cols = {c.name for c in t.columns if c.unique}
        for c in t.columns:
            notes = []
            if c.primary_key:
                notes.append("primary key")
            if c.name in unique_cols:
                notes.append("unique")
            for fk in c.foreign_keys:
                notes.append(f"→ `{fk.column.table.name}.{fk.column.name}`")
            for child, col, parent in SOFT_LINKS:
                if child == t.name and col == c.name:
                    notes.append(f"→ `{parent}.id` (not enforced by the database)")
            if c.default is not None and getattr(c.default, "is_scalar", False):
                notes.append(f"default `{c.default.arg}`")
            out.append(
                f"| `{c.name}` | {_type(c)} | {'no' if c.nullable and not c.primary_key else 'yes'} | {'; '.join(notes)} |"
            )
        extras = []
        for ix in sorted(t.indexes, key=lambda i: i.name or ""):
            cols = ", ".join(c.name for c in ix.columns)
            where = ix.dialect_options["sqlite"].get("where")
            extras.append(
                f"{'unique ' if ix.unique else ''}index `{ix.name}` on ({cols})"
                + (f" where `{where}`" if where is not None else "")
            )
        if extras:
            out += ["", "Indexes: " + "; ".join(extras) + "."]
        out.append("")
    return "\n".join(out)


def roles_matrix() -> list[str]:
    from aisys.auth.permissions import PERMISSIONS, ROLES

    names = list(ROLES)
    out = [
        "## Roles and permissions",
        "",
        "Each person has one role; a role is a set of permissions, and every endpoint names the permission it needs.",
        "",
    ]
    out.append("| Permission | What it allows | " + " | ".join(names) + " |")
    out.append("|---|---|" + "---|" * len(names))
    for code, text in PERMISSIONS.items():
        out.append(f"| `{code}` | {text} | " + " | ".join("yes" if code in ROLES[n][1] else "" for n in names) + " |")
    out += ["", *[f"- **{n}**: {ROLES[n][0]}" for n in names], ""]
    return out


def _permissions(dependant) -> list[str]:
    found = []
    for dep in dependant.dependencies:
        perm = getattr(dep.call, "permission", None)
        if perm:
            found.append(perm)
        found += _permissions(dep)
    return found


def _needs_login(dependant) -> bool:
    for dep in dependant.dependencies:
        if getattr(dep.call, "__name__", "") in ("get_principal", "dependency") or _needs_login(dep):
            return True
    return False


def api_reference() -> str:
    from aisys.app import create_app
    from aisys.config import Settings

    with tempfile.TemporaryDirectory() as tmp:
        settings = Settings(
            database_url=f"sqlite:///{Path(tmp, 'doc.db').as_posix()}",
            backup_dir=str(Path(tmp, "bk")),
            log_level="CRITICAL",
        )
        app = create_app(settings)
        rows: dict[str, list[tuple]] = defaultdict(list)
        flat = []
        for r in app.routes:  # included routers are wrapped; their routes already carry their full paths
            flat += list(r.original_router.routes) if hasattr(r, "original_router") else [r]
        for route in flat:
            if not isinstance(route, APIRoute) or not route.path.startswith(("/api", "/health")):
                continue
            perms = sorted(set(_permissions(route.dependant)))
            who = ", ".join(f"`{p}`" for p in perms) or (
                "any signed-in user" if _needs_login(route.dependant) else "public"
            )
            purpose = inspect.getdoc(route.endpoint) or ""
            purpose = purpose.split("\n\n")[0].replace("\n", " ")[:160]
            tag = (route.tags or ["other"])[0]
            for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
                rows[tag].append((route.path, method, who, purpose, "/mock/" in route.path))
        engine = app.state.engine
        engine.dispose()
    total = sum(len(v) for v in rows.values())
    out = [
        "# API reference",
        "",
        "_Generated by `python scripts/gen_docs.py` from the application's routes. Do not edit by hand._",
        "",
        f"{total} endpoints. Every endpoint returns JSON (or CSV for exports) and needs a session (a cookie, or an",
        "`Authorization: Bearer <token>` header from `/api/auth/card-login` or `/api/auth/login`) unless it says **public**.",
        'Errors are `{"detail": {"message": ..., "problems": [...]}}` or `{"detail": "..."}` with a normal HTTP status',
        "(401 not signed in, 403 missing permission, 404, 409 conflict, 422 invalid input, 429 too many, 503 restore running).",
        "Endpoints under `/mock/` are development simulators and return 404 when `environment = production`.",
        "The interactive version (with request and response shapes) is served by the application at `/docs`.",
        "",
    ]
    for tag in sorted(rows):
        out += [f"## {tag}", "", "| Method | Path | Who may call it | What it does |", "|---|---|---|---|"]
        for path, method, who, purpose, dev in sorted(rows[tag]):
            out.append(f"| {method} | `{path}`{' (dev only)' if dev else ''} | {who} | {purpose} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    wanted = {OUT_DATA: data_dictionary(), OUT_API: api_reference()}
    stale = [p.name for p, text in wanted.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            print("out of date:", ", ".join(stale), "- run python scripts/gen_docs.py")
            return 1
        return 0
    for path, text in wanted.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
