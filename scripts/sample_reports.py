"""Write the committed sample reports in docs/samples/.

    python scripts/sample_reports.py [--check]

Imports samples/library_200.xlsx into a throw-away database as the librarian, downloads the validation problems
(the same CSV the Data migration page offers), commits the batch and saves the reconciliation (the JSON the commit
returns). Both are written to docs/samples/. The output is deterministic: it holds no timestamps, no batch file
paths and no checksums that vary. With --check nothing is written; the script exits 1 if the committed files differ.
"""

# ruff: noqa: E501  (this script writes prose into documents)
from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from fastapi.testclient import TestClient  # noqa: E402

from shelfsense.app import create_app  # noqa: E402
from shelfsense.cli import seed_demo  # noqa: E402
from shelfsense.config import Settings  # noqa: E402

SOURCE = REPO / "samples" / "library_200.xlsx"
OUT = REPO / "docs" / "samples"

README = """# Sample import reports

Synthetic, generated by `python scripts/sample_reports.py` from `samples/library_200.xlsx` (200 rows, seed 42; the
deliberate defects are listed in `samples/library_200.manifest.json`). Nothing here is real library data. Running the
script again gives the same files; `python scripts/sample_reports.py --check` says whether these files are current.

The import was run as the librarian against an empty demo database. The validation report was downloaded after
validation and before the commit; the reconciliation is what the commit returned.

## validation-report.csv

The problem list for a batch on the **Data migration** page (`GET /api/migrations/{id}/errors.csv`).
One line per problem, so a row with two problems appears twice. Rows without a problem do not appear.

| Column | Meaning |
|---|---|
| `row_no` | The row as a person sees it in the spreadsheet (the header is row 1) |
| `row_status` | `invalid` (rejected, would corrupt the catalogue), `duplicate` (skipped, accession number or barcode already seen) or `valid` (kept, with a warning) |
| `severity` | `error` (the row is rejected) or `warning` (the row is kept, the value was dropped or changed) |
| `field` | The target field the problem is about |
| `code` | A short code, for example `isbn_invalid`, `date_invalid`, `year_invalid`; the full list is in `docs/migration.md` |
| `message` | The problem in plain words |
| `duplicate_of` | For a duplicate: the earlier row or the existing library record it repeats |
| remaining columns | The original cells of that row, exactly as uploaded, so the line can be fixed without opening the file twice |

A cell that starts with `=`, `+`, `-` or `@` is written with a leading `'` so a spreadsheet cannot run it.

## reconciliation-report.json

The proof, written by the commit, that every source row is accounted for and that existing records were not touched.

| Field | Meaning |
|---|---|
| `source_rows` | Data rows in the file (without the header) |
| `migrated` | Valid rows inserted as items |
| `rejected_invalid` | Rows refused because of an error |
| `skipped_duplicate` | Rows skipped as duplicates |
| `items_before`, `items_after`, `items_added` | Item count in the library before and after the commit, and the difference |
| `bibs_before`, `bibs_after`, `bibs_created` | The same for bibliographic records (copies of one title share one record, so there are fewer records than items) |
| `existing_records_unchanged` | `true` when a fingerprint of the records that existed before the commit is the same after it |
| `balanced` | `true` only when `source_rows = migrated + rejected_invalid + skipped_duplicate`, items added equals rows migrated equals items carrying this batch, new bibliographic records equal those carrying this batch, and the existing records are unchanged |

Also in the file: `batch_summary` (the counts the validation found, before the commit) and `warnings_by_code` (how many
rows were kept with each warning).
"""


def build(tmp: Path) -> tuple[str, dict]:
    settings = Settings(
        database_url=f"sqlite:///{(tmp / 'sample.db').as_posix()}", backup_dir=str(tmp / "bk"), log_level="CRITICAL"
    )
    app = create_app(settings)
    seed_demo(settings)
    with TestClient(app) as c:
        token = c.post("/api/auth/card-login", json={"uid": "STAFFLIB0001"}).json()["token"]
        lib = {"Authorization": f"Bearer {token}"}
        r = c.post("/api/migrations", headers=lib, files={"file": (SOURCE.name, SOURCE.read_bytes())})
        r.raise_for_status()
        batch = r.json()
        bid = batch["id"]
        csv_text = c.get(f"/api/migrations/{bid}/errors.csv", headers=lib).content.decode("utf-8")
        validated = {k: v for k, v in batch["summary"].items() if isinstance(v, int)}
        warnings: dict[str, int] = {}
        rows = c.get(f"/api/migrations/{bid}/rows", headers=lib, params={"limit": 500}).json()["rows"]
        for row in rows:
            for issue in row["errors"]:
                if issue["severity"] == "warning":
                    warnings[issue["code"]] = warnings.get(issue["code"], 0) + 1
        r = c.post(f"/api/migrations/{bid}/commit", headers=lib)
        r.raise_for_status()
        rec = r.json()["summary"]["reconciliation"]
    report = {
        "source_file": SOURCE.name,
        **rec,
        "batch_summary": validated,
        "warnings_by_code": dict(sorted(warnings.items())),
    }
    # Normalise line endings so the files are the same on every platform.
    return csv_text.replace("\r\n", "\n"), report


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare with the committed files; write nothing")
    args = ap.parse_args()
    # Windows keeps the SQLite file open until the process ends, so a failed clean-up of the temp folder is ignored.
    with tempfile.TemporaryDirectory(prefix="shelfsense-samples-", ignore_cleanup_errors=True) as d:
        csv_text, report = build(Path(d))
    files = {
        "validation-report.csv": csv_text,
        "reconciliation-report.json": json.dumps(report, indent=2, sort_keys=True) + "\n",
        "README.md": README,
    }
    if args.check:
        stale = [n for n, t in files.items() if not (OUT / n).exists() or (OUT / n).read_text("utf-8") != t]
        print("stale: " + ", ".join(stale) if stale else "docs/samples is current")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print("wrote", (OUT / name).relative_to(REPO))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
