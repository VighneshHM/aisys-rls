"""Generate docs/traceability.md from docs/requirements.csv + @pytest.mark.req(...) markers in tests/.

Usage: python scripts/trace.py
"""

from __future__ import annotations

import ast
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _req_ids(node: ast.expr) -> list[str]:
    is_req = isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "req"
    return [ast.literal_eval(arg) for arg in node.args] if is_req else []


def collect_evidence() -> dict[str, list[str]]:
    evidence: dict[str, list[str]] = defaultdict(list)
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        module_ids = []  # `pytestmark = pytest.mark.req(...)` covers every test in the file
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "pytestmark" for t in node.targets
            ):
                module_ids = _req_ids(node.value)
        for node in ast.walk(tree):
            if not isinstance(node, ast.FunctionDef) or not node.name.startswith("test_"):
                continue
            ids = list(module_ids)
            for deco in node.decorator_list:
                ids += [i for i in _req_ids(deco) if i not in ids]
            for rid in ids:
                evidence[rid].append(f"{path.name}::{node.name}")
    return evidence


def main() -> None:
    evidence = collect_evidence()
    with (ROOT / "docs" / "requirements.csv").open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    ids = {r["id"] for r in rows}
    unknown = set(evidence) - ids
    if unknown:
        raise SystemExit(f"tests reference unknown requirement IDs: {sorted(unknown)}")

    out = [
        "# Requirements traceability matrix",
        "",
        "_Generated by `python scripts/trace.py` from `docs/requirements.csv` and the `@pytest.mark.req` markers._",
        "_Status is maintained by hand in the CSV; the evidence column is generated._",
        "",
        "| ID | Area | Status | Tests (evidence) | Notes |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        tests = evidence.get(r["id"], [])
        ev = f"{len(tests)} test(s)" if tests else "-"
        out.append(f"| {r['id']} | {r['area']} | {r['status']} | {ev} | {r['notes']} |")
    out += ["", "## Test detail", ""]
    for rid in sorted(evidence):
        out.append(f"- **{rid}**: " + ", ".join(f"`{t}`" for t in evidence[rid]))
    done = sum(r["status"] == "done" for r in rows)
    out += ["", f"Summary: {done}/{len(rows)} done, {sum(r['status'] == 'partial' for r in rows)} partial.", ""]
    (ROOT / "docs" / "traceability.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote docs/traceability.md ({len(rows)} requirements, {sum(map(len, evidence.values()))} links)")


if __name__ == "__main__":
    main()
